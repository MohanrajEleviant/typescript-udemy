let x:number=10;
let y:number=10;
let z:number=10;

x++;
console.log("**** Post & Pre Increment ****")
console.log(x);     // 11
console.log(y++);   // 10
console.log(++z);   // 11

let p:number=10;
let q:number=10;
let r:number=10;

p--;
console.log("**** Post & Pre Decrement ****")
console.log(p); // 9
console.log(q--);   // 10
console.log(--r);   // 9