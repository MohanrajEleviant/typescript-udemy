let x1:number=10;
let y1:number=10;
let z1:number=10;

x1++;
console.log("**** Post & Pre Increment ****")
console.log(x1);     // 11
console.log(y1++);   // 10
console.log(++z1);   // 11

let p:number=10;
let q:number=10;
let r:number=10;

p--;
console.log("**** Post & Pre Decrement ****")
console.log(p); // 9
console.log(q--);   // 10
console.log(--r);   // 9